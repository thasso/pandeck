import { useCallback, useMemo, useState } from "react";
import type { DisplayMessage } from "@assistant/shared";
import { setupGreeting } from "../lib/firstRun.ts";
import { AssistantMessage } from "./AssistantMessage.tsx";
import { ErrorNote } from "./common/load.tsx";
import { PageHeader } from "./PageHeader.tsx";
import type { TranscriptViewPrefs } from "./transcriptView.ts";
import { Button } from "./ui/button.tsx";

/** The greeting has text only, so no transcript flag changes what it shows. */
const GREETING_VIEW: TranscriptViewPrefs = {
  showThinking: false,
  showTools: false,
  expandThinking: false,
  expandTools: false,
  wrapToolLines: false,
};

/**
 * @component GuidedSetupGreeting
 * @purpose The first message of the guided setup chat: an app-authored
 * greeting, rendered as an assistant message, that says the account is
 * connected and asks whether to keep the assistant's name.
 * @useWhen Above the Personal Assistant's transcript while first run is in
 * guided setup (`docs/onboarding.md`), as the transcript's `intro` or, before
 * the first message, in its place.
 * @avoidWhen Anything stored: it is never written to the session and never
 * generated by a model. The setup prompt tells the assistant it was shown.
 */
export function GuidedSetupGreeting({
  assistantName,
}: {
  /** The saved assistant name; an unsaved one is introduced as Larry. */
  assistantName: string;
}) {
  const message = useMemo<DisplayMessage>(
    () => ({
      id: "guided-setup-greeting",
      role: "assistant",
      blocks: [{ kind: "text", text: setupGreeting(assistantName) }],
    }),
    [assistantName],
  );
  return (
    <section aria-label="Setup greeting" data-role="assistant">
      <AssistantMessage message={message} view={GREETING_VIEW} />
    </section>
  );
}

/**
 * @component GuidedSetupHeader
 * @purpose The guided setup chat's header: it names the screen and holds
 * Finish setup, which ends first run and brings back the normal shell.
 * @useWhen Over the Personal Assistant's chat while first run is in guided
 * setup (`docs/onboarding.md`), in place of the chat header.
 * @intent A failed finish stays here, on the button that failed; success is
 * the server's broadcast, which removes this header.
 */
export function GuidedSetupHeader({
  onFinish,
}: {
  onFinish: () => Promise<unknown>;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const finish = useCallback(async () => {
    setBusy(true);
    setError(null);
    try {
      await onFinish();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : String(cause));
    } finally {
      setBusy(false);
    }
  }, [onFinish]);
  return (
    <>
      <PageHeader
        density="compact"
        title="Welcome to Pandeck"
        actions={
          <Button busy={busy} onClick={() => void finish()}>
            Finish setup
          </Button>
        }
      />
      {error ? (
        <div className="mx-auto w-full max-w-3xl px-4 pt-2">
          <ErrorNote message={error} />
        </div>
      ) : null}
    </>
  );
}

import type {
  CredentialProfileProvider,
  CredentialProfileSummary,
  ModelOption,
} from "@assistant/shared";
import {
  ACCOUNT_KINDS,
  DEFAULT_PERMANENT_ASSISTANT_NAME,
  FIRST_RUN_ASSISTANT_NAME,
} from "@assistant/shared";

/** The account kinds the first account card offers, in its order. */
const FIRST_ACCOUNT_KINDS: readonly CredentialProfileProvider[] = [
  "claude",
  "openai-codex",
  "openai-compatible",
];

/**
 * What the card does for an account of one kind:
 * - `create`: add a new account (named after its kind) and sign it in, or for
 *   an endpoint open its Settings section;
 * - `enable`: the account exists but is disabled;
 * - `sign-in` / `continue-sign-in`: a login account is not signed in, or its
 *   login is still running;
 * - `enable-claude`: a signed-in Claude account that offers nothing because the
 *   Claude SDK integration is off;
 * - `finish-endpoint`: an endpoint without a base URL or models yet.
 */
type FirstAccountAction =
  | "create"
  | "enable"
  | "sign-in"
  | "continue-sign-in"
  | "enable-claude"
  | "finish-endpoint";

export interface FirstAccountStep {
  kind: CredentialProfileProvider;
  action: FirstAccountAction;
  /** The existing account the step continues; absent for `create`. */
  profile?: CredentialProfileSummary;
}

function stepFor(
  profile: CredentialProfileSummary,
  models: readonly ModelOption[],
): FirstAccountAction {
  if (!profile.enabled) return "enable";
  if (ACCOUNT_KINDS[profile.provider].credential === "endpoint")
    return "finish-endpoint";
  if (profile.status === "connecting") return "continue-sign-in";
  if (profile.status === "ready" && profile.provider === "claude")
    return models.length === 0 ? "enable-claude" : "sign-in";
  return "sign-in";
}

/**
 * One step per offered kind. An earlier account of that kind is continued
 * rather than a second one created, so an interrupted sign-in resumes on the
 * same account; an enabled one is preferred over a disabled one.
 */
export function firstAccountSteps(
  profiles: readonly CredentialProfileSummary[],
  modelsByProfile: Readonly<Record<string, readonly ModelOption[]>>,
): FirstAccountStep[] {
  return FIRST_ACCOUNT_KINDS.map((kind) => {
    const ofKind = profiles.filter((profile) => profile.provider === kind);
    const profile =
      ofKind.find((candidate) => candidate.enabled) ?? ofKind[0] ?? undefined;
    return profile
      ? {
          kind,
          action: stepFor(profile, modelsByProfile[profile.id] ?? []),
          profile,
        }
      : { kind, action: "create" };
  });
}

/**
 * The assistant's name as the welcome introduces it: the saved one, or Larry
 * when none is saved. Settings fill an unsaved name in with the default, so a
 * name equal to the default counts as unsaved; the server saves Larry when
 * first run ends (`onboarding.ts`).
 */
export function firstRunAssistantName(savedName: string): string {
  const name = savedName.trim();
  return name && name !== DEFAULT_PERMANENT_ASSISTANT_NAME
    ? name
    : FIRST_RUN_ASSISTANT_NAME;
}

/** The assistant's name as plain text inside Markdown. */
function markdownPlain(text: string): string {
  return text
    .trim()
    .replace(/\s+/g, " ")
    .replace(/[\\`*_{}[\]()#+\-.!|<>~]/g, "\\$&");
}

/**
 * The app-authored greeting the first screen renders as an assistant message.
 * It is never stored and never generated by a model.
 */
export function welcomeGreeting(savedName: string): string {
  const name = markdownPlain(firstRunAssistantName(savedName));
  return [
    `Hi, I’m ${name}, your Personal Assistant in Pandeck. I’ll help you get settled in, and then we can get to work.`,
    "To reply at all, I need an AI account to run on. Connect one below: sign in with Claude or OpenAI (ChatGPT), or use an OpenAI-compatible endpoint. Sign-in happens outside this chat, and you can add or switch accounts later in Settings.",
  ].join("\n\n");
}

/**
 * The app-authored greeting above the guided setup chat (`docs/onboarding.md`).
 * The setup prompt tells the assistant the user has seen it, so the user's
 * first message answers its question. Never stored, never generated.
 */
export function setupGreeting(savedName: string): string {
  const name = markdownPlain(firstRunAssistantName(savedName));
  return [
    "Your account is connected, so I can reply now. Let’s set up a few basics together; you can skip any of them, or finish whenever you like.",
    `First, my name: I’m ${name}. Should I keep it, or would you like to call me something else?`,
  ].join("\n\n");
}
